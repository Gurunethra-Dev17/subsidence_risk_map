import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { compile } from 'json-schema-to-typescript'
import openapiTS, { astToString } from 'openapi-typescript'

const schemas = new URL('../../contracts/schemas/', import.meta.url)
const output = new URL('../types/', import.meta.url)
const banner = '/* Generated by npm run generate:types. Do not edit. */\n'
const files = (await readdir(schemas)).filter((file) => file.endsWith('.schema.json')).sort()
const declarations = await Promise.all(
  files.map(async (file) => {
    const schema = JSON.parse(await readFile(new URL(file, schemas), 'utf8'))
    return compile(schema, schema.title, { bannerComment: '', unknownAny: true })
  }),
)
const api = await openapiTS(new URL('api.openapi.yaml', schemas), { emptyObjectsUnknown: true })

await mkdir(output, { recursive: true })
await Promise.all([
  writeFile(new URL('contracts.ts', output), banner + declarations.join('\n')),
  writeFile(new URL('openapi.ts', output), banner + astToString(api)),
])
